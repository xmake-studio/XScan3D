const DICTS: Record<Lang, Dict> = { ru: ru as unknown as Dict, en: en as unknown as Dict };

export const i18n = $state({ lang: "ru" as Lang });

export function systemLang(): Lang {
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const l of langs) {
    const p = l.toLowerCase().slice(0, 2);
    if (p === "ru" || p === "uk" || p === "be" || p === "kk") return "ru";
    if (p === "en") return "en";
  }
  return "en";
}

function lookup(key: string, lang: Lang): string | Dict | undefined {
  let cur: string | Dict | undefined = DICTS[lang];
  for (const part of key.split(".")) {
    if (cur === undefined || typeof cur === "string") return undefined;
    cur = cur[part];
  }
  return cur;
}

/** Translates `key`, substituting {name} placeholders. */
export function t(key: string, params?: Record<string, string | number>): string {
  const v = lookup(key, i18n.lang) ?? lookup(key, "en");
  let s = typeof v === "string" ? v : key;
  if (params) for (const [k, val] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(val));
  return s;
}

/** Plural form for a count: Russian has three, English two. */
export function plural(key: string, n: number): string {
  const forms = lookup(`plural.${key}`, i18n.lang) as unknown as string[] | undefined;
  if (!forms) return key;
  if (i18n.lang === "ru") {
    const m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return forms[0];
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1];
    return forms[2];
  }
  return n === 1 ? forms[0] : forms[1];
}

export function locale(): string {
  return i18n.lang === "ru" ? "ru-RU" : "en-GB";
}
